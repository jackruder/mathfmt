#!/usr/bin/env python3
"""Generate packages.tsv: which package defines each command mathfmt emits.

For every control word in a spelling of latex.tsv or greek.tsv, and every
math-alphabet command of signatures.tsv, TeX is asked where it is defined:
in the LaTeX kernel, or after loading exactly one of the packages below
(the first in this order that defines it wins), or nowhere. The answer is
what `mathfmt declarations` uses to name the packages a preamble lacks.

Writes crates/mathfmt-core/data/packages.tsv. Needs pdflatex and lualatex
with the packages installed. Run by hand when a table gains a command or TeX
Live updates; review the diff.

    tools/gen-packages.py
"""

import re
import subprocess
import sys
import tempfile
from pathlib import Path

DATA = Path(__file__).resolve().parent.parent / "crates/mathfmt-core/data"

# (name in the table, engine, preamble line). Order is preference: a command
# several packages define is credited to the first.
SOURCES = [
    ("kernel", "pdflatex", ""),
    ("amsmath", "pdflatex", r"\usepackage{amsmath}"),
    ("amsfonts", "pdflatex", r"\usepackage{amsfonts}"),
    ("amssymb", "pdflatex", r"\usepackage{amssymb}"),
    ("bm", "pdflatex", r"\usepackage{bm}"),
    ("bbm", "pdflatex", r"\usepackage{bbm}"),
    ("mathrsfs", "pdflatex", r"\usepackage{mathrsfs}"),
    ("dsfont", "pdflatex", r"\usepackage{dsfont}"),
    ("unicode-math", "lualatex", r"\usepackage{unicode-math}"),
]

WORD = re.compile(r"\\([A-Za-z]+)")


def rows(name):
    for line in (DATA / name).read_text(encoding="utf-8").splitlines():
        if line.startswith("#") or not line.strip():
            continue
        yield line.split("\t")


def candidates():
    names = set()
    for row in rows("latex.tsv"):
        if len(row) > 1:
            names.update(WORD.findall(row[1]))
    for row in rows("greek.tsv"):
        names.update(WORD.findall(row[1]))
    for row in rows("signatures.tsv"):
        if len(row) > 2 and ("style=" in row[2] or "plain" in row[2].split()):
            names.add(row[0])
    return sorted(names)


def defined(engine, preamble, names, work):
    tex = [r"\documentclass{article}", preamble, r"\begin{document}"]
    tex.append(
        r"\def\probe#1{\ifcsname #1\endcsname"
        r"\expandafter\ifx\csname #1\endcsname\relax\else\typeout{DEFINED:#1:}\fi\fi}"
    )
    tex += [rf"\probe{{{n}}}" for n in names]
    tex.append(r"\end{document}")
    (work / "probe.tex").write_text("\n".join(tex) + "\n", encoding="utf-8")
    out = subprocess.run(
        [engine, "-interaction=nonstopmode", "-halt-on-error", "probe.tex"],
        cwd=work,
        capture_output=True,
        text=True,
        errors="replace",
    )
    if out.returncode != 0:
        sys.exit(f"{engine} failed with `{preamble}`:\n{out.stdout[-2000:]}")
    return set(re.findall(r"DEFINED:([A-Za-z]+):", out.stdout))


def main():
    names = candidates()
    where = {}
    with tempfile.TemporaryDirectory() as tmp:
        for source, engine, preamble in SOURCES:
            for n in defined(engine, preamble, names, Path(tmp)):
                where.setdefault(n, source)
    lines = [
        "# command\tdefined by",
        "# generated by tools/gen-packages.py; do not edit. `kernel` needs no package;",
        "# `-` is defined by none of the packages the script tries.",
    ]
    missing = []
    for n in names:
        lines.append(f"{n}\t{where.get(n, '-')}")
        if n not in where:
            missing.append(n)
    (DATA / "packages.tsv").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(names)} commands; {len(missing)} defined nowhere: {' '.join(missing)}")


if __name__ == "__main__":
    main()
