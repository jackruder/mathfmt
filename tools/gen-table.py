#!/usr/bin/env python3
"""Generate mathfmt's Unicode tables from unicode-math-table.tex.

Writes three TSV files under crates/mathfmt-core/data/:

  unicode-math.tsv   codepoint, unicode-math name, math class, description
                     (every row of the table, ASCII codepoints included)
  alphabets.tsv      codepoint, style, base   for styled letters and digits,
                     parsed from names such as \\mbfalpha, \\BbbR, \\mttzero
  greek.tsv          codepoint, LaTeX name    for the Greek letters LaTeX
                     (plus amssymb) defines, taken from the \\mup<name> rows

Run by hand when TeX Live updates; review the diff. The curated tables
latex.tsv and signatures.tsv are never touched by this script.

    tools/gen-table.py                # finds the table with kpsewhich
    tools/gen-table.py path/to/unicode-math-table.tex
"""

import re
import subprocess
import sys
from pathlib import Path

ROW = re.compile(
    r'^\\UnicodeMathSymbol\{"([0-9A-F]+)\}\{\\([A-Za-z]+)\s*\}\{\\(math[a-z]+)\}\{([^}]*)\}%?\s*$'
)

# Longest prefix first, so \mbfitsans is not read as \mbf + itsans.
PREFIXES = [
    ("mbfitsans", "bfsfit"),
    ("mbfsans", "bfsf"),
    ("mitsans", "sfit"),
    ("msans", "sf"),
    ("mbfscr", "bfscr"),
    ("mscr", "scr"),
    ("mbffrak", "bffrak"),
    ("mfrak", "frak"),
    ("mbfit", "bfit"),
    ("mbf", "bf"),
    ("mit", "it"),
    ("mtt", "tt"),
    ("Bbb", "bb"),
    # \mup<x> is the plain (upright) codepoint of Greek letters. It is not an
    # alphabet row: (α, up) prints as a wrapper, never as the bare letter, or
    # \mathrm{\alpha} would come back as α and lose its uprightness.
]

DIGITS = {
    "zero": "0", "one": "1", "two": "2", "three": "3", "four": "4",
    "five": "5", "six": "6", "seven": "7", "eight": "8", "nine": "9",
}

# Greek names LaTeX defines (kernel + amssymb's digamma and varkappa).
LATEX_GREEK = {
    "alpha", "beta", "gamma", "delta", "epsilon", "zeta", "eta", "theta",
    "iota", "kappa", "lambda", "mu", "nu", "xi", "pi", "rho", "sigma", "tau",
    "upsilon", "phi", "chi", "psi", "omega",
    "varepsilon", "vartheta", "varpi", "varrho", "varsigma", "varphi",
    "Gamma", "Delta", "Theta", "Lambda", "Xi", "Pi", "Sigma", "Upsilon",
    "Phi", "Psi", "Omega",
    "digamma", "varkappa",
}

# Bases that are symbols rather than letters, allowed under a style prefix.
SYMBOL_BASES = {"nabla": 0x2207, "partial": 0x2202}


def find_table() -> Path:
    out = subprocess.run(
        ["kpsewhich", "unicode-math-table.tex"], capture_output=True, text=True
    )
    if out.returncode != 0 or not out.stdout.strip():
        sys.exit("kpsewhich could not find unicode-math-table.tex; pass its path")
    return Path(out.stdout.strip())


def main() -> None:
    table = Path(sys.argv[1]) if len(sys.argv) > 1 else find_table()
    root = Path(__file__).resolve().parent.parent
    data = root / "crates" / "mathfmt-core" / "data"
    data.mkdir(parents=True, exist_ok=True)

    rows = []
    for line in table.read_text(encoding="utf-8").splitlines():
        m = ROW.match(line)
        if m:
            cp, name, cls, desc = m.groups()
            rows.append((int(cp, 16), name, cls, desc.strip()))
    if len(rows) < 2000:
        sys.exit(f"only {len(rows)} rows parsed from {table}; the format changed?")

    # Plain Greek: \mup<name> -> codepoint. Used both for greek.tsv and as the
    # base of styled Greek rows.
    greek_base = {}
    for cp, name, cls, _ in rows:
        if name.startswith("mup") and cls == "mathalpha":
            greek_base[name[3:]] = cp
        elif name.startswith("up") and name[2:] in LATEX_GREEK and name[2:] not in greek_base:
            greek_base[name[2:]] = cp  # \updigamma: the table has no \mupdigamma

    with (data / "unicode-math.tsv").open("w", encoding="utf-8") as f:
        f.write("# codepoint\tname\tclass\tdescription\n")
        f.write("# generated by tools/gen-table.py from unicode-math-table.tex; do not edit\n")
        for cp, name, cls, desc in rows:
            f.write(f"{cp:04X}\t{name}\t{cls}\t{desc}\n")

    alphabet_rows = [
        (0x210E, "it", "h"),    # \Planckconst: the italic h fill-in
        (0x2111, "frak", "I"),  # \Im
        (0x211C, "frak", "R"),  # \Re
    ]
    unparsed = []
    for cp, name, cls, _ in rows:
        for prefix, style in PREFIXES:
            if not name.startswith(prefix):
                continue
            base_name = name[len(prefix):]
            base = None
            if len(base_name) == 1 and base_name.isascii() and base_name.isalpha():
                base = base_name
            elif base_name in DIGITS:
                base = DIGITS[base_name]
            elif base_name in greek_base:
                base = chr(greek_base[base_name])
            elif base_name in SYMBOL_BASES:
                base = chr(SYMBOL_BASES[base_name])
            if base is None:
                unparsed.append(name)
            else:
                alphabet_rows.append((cp, style, base))
            break

    with (data / "alphabets.tsv").open("w", encoding="utf-8") as f:
        f.write("# codepoint\tstyle\tbase\n")
        f.write("# generated by tools/gen-table.py; styled letters and digits with a codepoint\n")
        for cp, style, base in sorted(alphabet_rows):
            f.write(f"{cp:04X}\t{style}\t{base}\n")

    with (data / "greek.tsv").open("w", encoding="utf-8") as f:
        f.write("# codepoint\tlatex\n")
        f.write("# generated by tools/gen-table.py; Greek letters LaTeX and amssymb define\n")
        for name in sorted(LATEX_GREEK, key=lambda n: greek_base.get(n, 0)):
            if name in greek_base:
                f.write(f"{greek_base[name]:04X}\t\\{name}\n")
            else:
                print(f"warning: no \\mup{name} row in the table", file=sys.stderr)

    print(f"{len(rows)} rows, {len(alphabet_rows)} alphabet rows, "
          f"{sum(1 for n in LATEX_GREEK if n in greek_base)} greek names")
    if unparsed:
        print("styled names left out (no recognized base): " + " ".join(unparsed),
              file=sys.stderr)


if __name__ == "__main__":
    main()
